/* Build streamdeck/ACBreakz Board.streamDeckPlugin from streamdeck/plugin/src.

   Bakes the team artwork into icons.js as data URIs rather than loading it at runtime:
   the plugin page runs from file://, where fetch/XHR of a sibling file is blocked and
   canvas.toDataURL on a file:// image taints and throws. A baked map sidesteps both.

   The Supabase client is VENDORED for the same reason a CDN is wrong here — a deck that
   cannot paint because jsdelivr is slow is exactly the failure this plugin exists to end.

   Zip rules are the same trap as the profiles: jszip, forward slashes, explicit directory
   entries. PowerShell/.NET zips write backslash entries and Stream Deck rejects them
   silently.

     node scripts/build-sd-plugin.mjs                                                    */
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, rmSync } from "fs";
import { execFileSync } from "child_process";
import JSZip from "jszip";
import { FFDIR } from "./lib/pixels.mjs";

const ROOT = "C:/ACBreakz-Cloud";
const SRC = `${ROOT}/streamdeck/plugin/src`;
const OUT = `${ROOT}/streamdeck/plugin/build/com.acbreakz.board.sdPlugin`;
const TMP = `${ROOT}/streamdeck/plugin/build/tmp`;
const KEY_PX = 144;                    // Stream Deck keys are 72pt; 144 covers hi-dpi

for (const d of [OUT, `${OUT}/icons`, TMP]) { rmSync(d, { recursive: true, force: true }); }
for (const d of [OUT, `${OUT}/icons`, TMP]) mkdirSync(d, { recursive: true });

/* ---- team table straight out of the overlay config, so they cannot drift ---- */
const cfgSrc = readFileSync(`${ROOT}/overlay/config.js`, "utf8");
/* run the real config in a sandbox with just a window object, so this build cannot hold
   a stale copy of the team table */
const win = {};
/* config.js reads location.search for the ?pc= / ?layer= overrides; stub what it touches */
new Function("window", "location", "document", cfgSrc)(
  win, { search: "" }, { querySelector: () => null });
const { TEAMS, ORDER } = win.ACBZ;
console.log(`teams: ${ORDER.length}`);

/* ---- bake the artwork ---- */
const SETS = { normal: "normal", x: "x", glow: "glow" };
const icons = {};
let baked = 0, bytes = 0;
for (const [set, dir] of Object.entries(SETS)) {
  icons[set] = {};
  for (const abbr of ORDER) {
    const name = TEAMS[abbr]?.name;
    const srcPng = `${ROOT}/streamdeck/icons/${dir}/${name}.png`;
    if (!existsSync(srcPng)) { console.log(`  ! missing ${dir}/${name}.png`); continue; }
    const dst = `${TMP}/${set}-${abbr}.png`;
    execFileSync(`${FFDIR}/ffmpeg`, ["-v", "error", "-y", "-i", srcPng,
      "-vf", `scale=${KEY_PX}:${KEY_PX}:flags=lanczos`, dst]);
    const b64 = readFileSync(dst).toString("base64");
    icons[set][abbr] = `data:image/png;base64,${b64}`;
    baked++; bytes += b64.length;
  }
}
writeFileSync(`${OUT}/icons.js`, `window.ICONS = ${JSON.stringify(icons)};\n`);
console.log(`baked ${baked} images -> icons.js (${(bytes / 1048576).toFixed(2)} MB base64)`);

/* ---- config the plugin and its inspector share ---- */
const url = cfgSrc.match(/SUPABASE_URL:\s*"([^"]*)"/)[1];
const anon = cfgSrc.match(/SUPABASE_ANON_KEY:\s*"([^"]+)"/)[1];
/* Note for the profile builder: team keys must ship with NO States[0].Image. Stream Deck
   treats a profile-baked image as the user's own icon choice and it outranks setImage, so
   a baked logo silently swallows every repaint the plugin sends. All the artwork the deck
   needs is in icons.js below; the profile needs none of it. */

/* DECK_KEY is baked in from .env so that installing the plugin IS the whole install —
   there is no key to paste on each of five machines, and a machine that skips that step
   fails in the least obvious way available: the keys light up and paint correctly from
   realtime, and only a press does nothing but flash the alert triangle. This is the
   posture the profiles already have — every API Ninja url inside a .streamDeckProfile
   carries this same key in the clear. What keeps it out of the PUBLIC repo is .gitignore
   covering `streamdeck/plugin/build/` and `*.streamDeckPlugin`, so never commit either
   and never copy this generated config.js back into src/. A per-machine global setting
   still overrides it. */
const env = Object.fromEntries(readFileSync(`${ROOT}/.env`, "utf8").split(/\r?\n/)
  .filter(l => l.includes("=") && !l.startsWith("#"))
  .map(l => [l.slice(0, l.indexOf("=")).trim(), l.slice(l.indexOf("=") + 1).trim()]));
if (!env.DECK_KEY) { console.log("FATAL: no DECK_KEY in .env"); process.exit(1); }
writeFileSync(`${OUT}/config.js`,
  `/* generated by scripts/build-sd-plugin.mjs — DO NOT COMMIT: carries DECK_KEY. */\n` +
  `window.ACBZ_CFG = ${JSON.stringify({ SUPABASE_URL: url, SUPABASE_ANON_KEY: anon,
    DECK_KEY: env.DECK_KEY, TEAMS, ORDER }, null, 1)};\n`);

/* ---- vendor the realtime client ---- */
const VEND = `${ROOT}/streamdeck/plugin/vendor/supabase.min.js`;
if (!existsSync(VEND)) {
  mkdirSync(`${ROOT}/streamdeck/plugin/vendor`, { recursive: true });
  const js = await fetch("https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2/dist/umd/supabase.min.js")
    .then(r => r.text());
  writeFileSync(VEND, js);
  console.log(`vendored supabase.min.js (${(js.length / 1024).toFixed(0)} KB)`);
}
writeFileSync(`${OUT}/supabase.min.js`, readFileSync(VEND));

/* ---- plugin + inspector, and the icons the manifest names ---- */
for (const f of ["manifest.json", "plugin.html", "pi.html", "pi-reset.html"])
  writeFileSync(`${OUT}/${f}`, readFileSync(`${SRC}/${f}`));

/* manifest icons: reuse a team logo so the plugin is recognisable in the SD library */
const brand = `${ROOT}/streamdeck/icons/main/${readdirSync(`${ROOT}/streamdeck/icons/main`)[0]}`;
for (const [name, px] of [["plugin", 72], ["plugin@2x", 144], ["category", 28],
                          ["category@2x", 56], ["action", 20], ["action@2x", 40],
                          ["key", 72], ["key@2x", 144]]) {
  execFileSync(`${FFDIR}/ffmpeg`, ["-v", "error", "-y", "-i", brand,
    "-vf", `scale=${px}:${px}:flags=lanczos`, `${OUT}/icons/${name}.png`]);
}

/* ---- zip: forward slashes, directory entries, or Stream Deck silently refuses it ---- */
const zip = new JSZip();
const add = (dir, prefix) => {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = `${prefix}${e.name}`;
    if (e.isDirectory()) { zip.folder(p); add(`${dir}/${e.name}`, `${p}/`); }
    else zip.file(p, readFileSync(`${dir}/${e.name}`));
  }
};
zip.folder("com.acbreakz.board.sdPlugin");
add(OUT, "com.acbreakz.board.sdPlugin/");
const buf = await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE",
  compressionOptions: { level: 9 }, platform: "UNIX" });
const dest = `${ROOT}/streamdeck/ACBreakz Board.streamDeckPlugin`;
writeFileSync(dest, buf);
rmSync(TMP, { recursive: true, force: true });
console.log(`\n${dest}  ${(buf.length / 1048576).toFixed(2)} MB`);
console.log("install: double-click it on each PC (it replaces any previous version).");
